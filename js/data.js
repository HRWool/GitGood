function answerIsAccepted(accepted, value, acceptAny = false) {
  const normalized = value.trim().replace(/\s+/g, "");
  return (acceptAny && normalized.length > 0) || accepted.some((answer) => answer.trim().replace(/\s+/g, "") === normalized);
}

